"""math-quiz's data layer: session history, the in-progress draft, "flag for
review" bookmarks, the suite-wide mistake journal, confidence calibration and
this app's own settings.

Since the migration to ``common/`` this module is an **adapter**, not an
implementation.  The shared stores live in one place for all ten apps:

``common.datadir``  where the files are (``QUANTUM_STUDY_DATA_DIR``, resolved
                    at call time — no frozen module constants any more).
``common.journal``  ``mistakes.json`` / ``confidence.json``: locked,
                    atomic, other apps' rows preserved verbatim, and the
                    growth cap trims **only our own** rows.
``common.flags``    ``math_flagged.json``: atomic, rewritten from the raw
                    list so a row we do not understand is never deleted.
``common.schema``   a version sidecar, forward migration and a rotating
                    backup for every file this app writes.

What stays here is what is genuinely math-quiz's own: the *shape* of a session
record, the SRS weighting, the two id functions (a question generated by
Claude has no identity except a hash of its text), and the signatures the
screens already call — every public name below behaves as it did, so the UI,
``coach.py`` and ``dashboard.py`` are untouched.
"""

